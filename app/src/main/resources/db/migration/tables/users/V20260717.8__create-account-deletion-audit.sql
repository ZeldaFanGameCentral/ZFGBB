create table if not exists zfgbb.account_deletion_audit (
	deletion_id integer not null primary key generated by default as identity (sequence name seq_account_deletion_audit_deletion_id),
	subject_user_id_snapshot integer not null,
	subject_pseudonym varchar(64) not null,
	mode varchar(16) not null,
	initiated_by varchar(16) not null,
	requested_ts timestamptz default current_timestamp not null,
	confirmed_ts timestamptz,
	executed_ts timestamptz,
	message_count integer,
	content_resource_count integer,
	created_ts timestamptz default current_timestamp not null,
	updated_ts timestamptz default current_timestamp not null
);
